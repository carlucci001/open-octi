// What an agent says about its own voice engine must come from the running
// session, never from stored persona text. Matilda's profile still named her
// old provider after she moved to Gemini, and she repeated it to Carl.
const PROVIDER_LABELS = {
  gemini: 'Google Gemini Live',
  openai: 'OpenAI Realtime',
}

export function voiceRuntimeFact(provider) {
  const label = PROVIDER_LABELS[provider]
  if (!label) return ''
  return `Runtime fact, authoritative over everything else in these instructions: in this session your voice is generated by ${label}. If asked which provider, engine, or company powers your voice, answer ${label}. Any other voice provider named in your profile or instructions is out of date for you; never state it as your own.`
}
