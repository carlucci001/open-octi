import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { describe, expect, it } from 'vitest'
import { NAVIGATION_MANIFEST as PRIVATE_NAVIGATION_MANIFEST } from '../lib/navigation-manifest.js'

import {
  assertSafeOutput,
  createOpenOctiNavigationManifestSource,
  SOURCE_ROOT,
  matchOpenOctiDenylist,
  neutralizeOpenOctiReferences,
  scanOpenOctiDenylist,
  validatePublicStarterData,
  listFiles,
} from '../scripts/export-openocti.mjs'

// In the exported tree the canonical manifest is already the generated public one,
// so assertions about private destinations in the source only apply to the private tree.
const CANONICAL_MANIFEST_IS_GENERATED = fs.readFileSync(path.join(SOURCE_ROOT, 'lib/navigation-manifest.js'), 'utf8').toLowerCase().startsWith('// generated by scripts/export-openocti')

const joined = (...parts) => parts.join('')

describe('Public starter data isolation', () => {
  const read = name => JSON.parse(fs.readFileSync(path.join(SOURCE_ROOT, 'data-demo', name), 'utf8'))
  const validate = agents => validatePublicStarterData(agents, read('voice-agent-roster.json'), read('voice-agent.json'))
  it('accepts only the reviewed public agent shape', () => {
    expect(validate(read('agents.json'))).toBe(true)
  })
  it('rejects extra agents, tool grants, and credential fields', () => {
    for (const mutate of [
      data => { data.agents.extra = data.agents.main },
      data => { data.agents.main.tools = ['private_tool'] },
      data => { data.agents.main.apiKey = 'installation-value' },
      data => { data.agents.main.voice = { agentId: 'provider-binding' } },
    ]) {
      const agents = read('agents.json')
      mutate(agents)
      expect(() => validate(agents)).toThrow()
    }
  })
  it('rejects provider bindings in the voice roster', () => {
    const roster = read('voice-agent-roster.json')
    roster.main.agentId = 'installation-agent'
    expect(() => validatePublicStarterData(read('agents.json'), roster, read('voice-agent.json'))).toThrow()
  })
})

describe('OpenOcti export destination safety', () => {
  it('excludes retained Git metadata from release inventories and hashes', () => {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), 'openocti-inventory-'))
    try {
      fs.mkdirSync(path.join(root, '.git'))
      fs.writeFileSync(path.join(root, '.git', 'config'), 'local repository metadata')
      fs.writeFileSync(path.join(root, 'README.md'), 'Public source')
      expect(listFiles(root).map(file => path.relative(root, file))).toEqual(['README.md'])
    } finally { fs.rmSync(root, { recursive: true, force: true }) }
  })
  it('allows separate release and merged exports without allowing arbitrary cleanup targets', () => {
    for (const name of ['openocti-export', 'openocti-export-merged']) {
      expect(() => assertSafeOutput(path.join(os.tmpdir(), name))).not.toThrow()
    }
    for (const target of [path.parse(SOURCE_ROOT).root, SOURCE_ROOT, path.dirname(SOURCE_ROOT), path.join(os.tmpdir(), 'unrelated-project')]) {
      expect(() => assertSafeOutput(target)).toThrow()
    }
  })
})

describe('OpenOcti export product denylist', () => {
  it.skipIf(CANONICAL_MANIFEST_IS_GENERATED)('keeps private navigation in the canonical source while emitting only public manifest metadata', async () => {
    const privateMarker = ['get', 'found', '3'].join('')
    const canonical = fs.readFileSync(path.join(SOURCE_ROOT, 'lib/navigation-manifest.js'), 'utf8')
    const exported = createOpenOctiNavigationManifestSource()
    const root = fs.mkdtempSync(path.join(os.tmpdir(), 'openocti-navigation-manifest-'))

    try {
      expect(canonical.toLowerCase()).toContain(privateMarker)
      expect(PRIVATE_NAVIGATION_MANIFEST.destinations.some(item => item.id === privateMarker)).toBe(true)
      expect(exported.toLowerCase()).not.toContain(privateMarker)
      expect(matchOpenOctiDenylist(exported)).toEqual([])

      fs.mkdirSync(path.join(root, 'lib'), { recursive: true })
      const exportedFile = path.join(root, 'lib/navigation-manifest.mjs')
      fs.writeFileSync(exportedFile, exported)
      expect(() => scanOpenOctiDenylist(root)).not.toThrow()

      const publicManifest = await import(`data:text/javascript;base64,${Buffer.from(exported).toString('base64')}`)
      expect(publicManifest.navigationManifestFor().edition).toBe('openocti')
      expect(publicManifest.NAVIGATION_MANIFEST.destinations.some(item => item.id === privateMarker)).toBe(false)
      expect(publicManifest.NAVIGATION_MANIFEST.destinations.every(item => item.editions.includes('openocti'))).toBe(true)

      fs.appendFileSync(exportedFile, `\n// ${privateMarker}\n`)
      expect(() => scanOpenOctiDenylist(root)).toThrow(/lib[\\/]navigation-manifest\.mjs:/)
    } finally {
      fs.rmSync(root, { recursive: true, force: true })
    }
  })

  it.each([
    ['search product prefix', joined('get', 'found')],
    ['remediation product prefix', joined('get', 'remedy')],
    ['video product', joined('my', 'vtc')],
    ['news product compact', joined('newsroom', 'aios')],
    ['news product hyphenated', joined('newsroom-', 'aios')],
    ['workflow product', joined('vibn', 'flow')],
    ['flip product', joined('vibn', 'flip')],
    ['alternate workflow spelling', joined('vibin', 'flow')],
    ['owner domain', joined('carl', 'farrington.com')],
    ['company domain', joined('farrington', 'development.com')],
    ['production host label', joined('fcc-', 'prod')],
    ['telephone href', joined('tel:', '+', '1828', '7709227')],
    ['private city', joined('Ashe', 'ville')],
    ['owner personal identifier', joined('carl', 'farring')],
    ['closed search suite', joined('Search', 'Suite')],
    ['closed content suite', joined('Content', 'Hub')],
    ['private publication id', joined('wnc', '_times')],
    ['private knowledge label', joined('Farrington', ' Knowledge')],
    ['private mail label', joined('Command Center', ' Mail')],
    ['personal home path', joined('/home/', 'carl')],
  ])('matches %s case-insensitively', (_label, value) => {
    expect(matchOpenOctiDenylist(value.toUpperCase())).not.toEqual([])
  })

  it.each([
    joined('octi', 'cc.com'),
    joined('open', 'octi.com'),
    'Your company',
    'https://example.com',
  ])('allows public or neutral value %s', (value) => {
    expect(matchOpenOctiDenylist(value)).toEqual([])
  })

  it('scans service files and reports file:line diagnostics', () => {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), 'openocti-denylist-'))
    try {
      fs.writeFileSync(path.join(root, 'sample.service'), joined('company=https://farrington', 'development.com'))
      expect(() => scanOpenOctiDenylist(root)).toThrow(/sample\.service:1:/)
    } finally {
      fs.rmSync(root, { recursive: true, force: true })
    }
  })

  it('allows the explicitly portable NC lead-source pack but not unrelated private-city references', () => {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), 'openocti-denylist-'))
    try {
      const city = joined('ashe', 'ville')
      const allowed = path.join(root, 'vault', 'lead-sources', 'city')
      fs.mkdirSync(allowed, { recursive: true })
      fs.writeFileSync(path.join(allowed, `${city}-permits.md`), `${city} public API`)
      expect(() => scanOpenOctiDenylist(root)).not.toThrow()
      fs.writeFileSync(path.join(root, 'unrelated.md'), city)
      expect(() => scanOpenOctiDenylist(root)).toThrow(/unrelated\.md:1:/)
    } finally {
      fs.rmSync(root, { recursive: true, force: true })
    }
  })

  it.each([
    [joined('tel:', '+', '1828', '7709227'), 'tel:PHONE_REDACTED'],
    [joined('(828)', ' 770-9227'), 'PHONE_REDACTED'],
    [joined('phone: ', '828', '770', '9227'), 'phone: PHONE_REDACTED'],
    [joined('Ashe', 'ville, NC'), 'City, ST'],
    [joined('carl', 'farring'), 'workspace-owner'],
    [joined('Search', 'Suite'), 'SearchTools'],
    [joined('Content', 'Hub'), 'ContentStudio'],
    [joined('wnc', '_times'), 'sample_business'],
    [joined('Farrington', ' Knowledge'), 'Knowledge'],
    [joined('Command Center', ' Mail'), 'Mail'],
    [joined('/home/', 'carl', '/dev/project'), '/srv/openocti/dev/project'],
  ])('neutralizes private contact value %s', (value, expected) => {
    expect(neutralizeOpenOctiReferences(value)).toBe(expected)
  })
})
